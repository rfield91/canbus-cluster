// Converts a photo into the boot logo: an LVGL v8 true-colour (RGB565) image
// compiled into the firmware.
//
//   cd tools && npm install && npm run image                 # assets/boot.jpg
//   node image.mjs <input> [--fit cover|contain]
//
// cover (default) fills the 800x480 screen and crops what overhangs.
// contain shows the whole photo with black bars. Either way the result is
// opaque RGB565, so drawing it costs no per-pixel alpha blending.

import sharp from 'sharp';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, basename } from 'node:path';

const W = 800, H = 480;
const NAME = 'boot_logo';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const args = process.argv.slice(2);
const fitIdx = args.indexOf('--fit');
const fit = fitIdx >= 0 ? args.splice(fitIdx, 2)[1] : 'cover';
const input = args[0] ?? join(root, 'assets', 'boot.jpg');
const out = join(root, 'main', 'ui', 'images', `${NAME}.c`);

const { data, info } = await sharp(input)
    .rotate()                                   // honour EXIF orientation
    .resize(W, H, { fit, background: '#000000' })
    .flatten({ background: '#000000' })
    .removeAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });

// RGB565, little-endian: CONFIG_LV_COLOR_16_SWAP is off.
const px = Buffer.alloc(info.width * info.height * 2);
for (let i = 0, o = 0; i < data.length; i += 3, o += 2) {
    const v = ((data[i] >> 3) << 11) | ((data[i + 1] >> 2) << 5) | (data[i + 2] >> 3);
    px[o] = v & 0xFF;
    px[o + 1] = v >> 8;
}

const rows = [];
for (let i = 0; i < px.length; i += 24)
    rows.push('  ' + [...px.subarray(i, i + 24)].map(b => '0x' + b.toString(16).padStart(2, '0')).join(','));

writeFileSync(out, `// Generated by tools/image.mjs from ${basename(input)} (${fit}). Do not edit.
#include "lvgl.h"

static const LV_ATTRIBUTE_LARGE_CONST uint8_t ${NAME}_map[] = {
${rows.join(',\n')}
};

const lv_img_dsc_t ${NAME} = {
  .header.cf = LV_IMG_CF_TRUE_COLOR,
  .header.always_zero = 0,
  .header.reserved = 0,
  .header.w = ${info.width},
  .header.h = ${info.height},
  .data_size = ${px.length},
  .data = ${NAME}_map,
};
`);
console.log(`wrote ${out}: ${info.width}x${info.height}, ${px.length} bytes`);
