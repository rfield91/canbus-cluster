// Generates the dash's LVGL fonts from Montserrat (the same face as LVGL's
// built-in fonts) with lv_font_conv.
//
//   cd tools && npm install && npm run fonts
//
// The TTF comes from the LVGL component, so run a build once first to fetch
// it into managed_components/.
//
// Numeric fonts get TABULAR digits: Montserrat's are proportional ("1" is
// narrow), so a changing reading would shuffle sideways. After conversion,
// every digit's advance is widened to the widest digit's and the glyph is
// centred in it.

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const TTF = join(root, 'managed_components', 'lvgl__lvgl', 'scripts', 'built_in_font', 'Montserrat-Medium.ttf');
const OUT = join(root, 'main', 'ui', 'fonts');
const CONV = join(root, 'tools', 'node_modules', 'lv_font_conv', 'lv_font_conv.js');

const DIGITS = [[0x30, 0x39]];
const NUMERIC = [[0x2D, 0x2E], ...DIGITS];                // - . 0-9
const TEXT = [[0x20, 0x7E], [0xB0, 0xB0], [0xB7, 0xB7]];  // ASCII ° ·

const FONTS = [
    { name: 'font_speed_150', size: 150, ranges: NUMERIC, tabular: true },
    { name: 'font_rpm_84',    size: 84,  ranges: NUMERIC, tabular: true },
    { name: 'font_value_46',  size: 46,  ranges: NUMERIC, tabular: true },
    { name: 'font_text_18',   size: 18,  ranges: TEXT,    tabular: false },
];

if (!existsSync(TTF)) {
    console.error(`missing ${TTF}\nrun idf.py build once so the LVGL component is downloaded`);
    process.exit(1);
}

const codepoints = ranges => ranges.flatMap(([a, b]) => Array.from({ length: b - a + 1 }, (_, i) => a + i));

// Rewrites the glyph_dsc entries of the digits. Entries follow the sorted
// codepoints, after the reserved id 0. adv_w is in 1/16 px.
function makeTabular(src, cps) {
    const start = src.indexOf('glyph_dsc[] = {');
    const end = src.indexOf('};', start);
    const re = /\{\.bitmap_index = (\d+), \.adv_w = (\d+), \.box_w = (\d+), \.box_h = (\d+), \.ofs_x = (-?\d+), \.ofs_y = (-?\d+)\}/g;
    const entries = [...src.slice(start, end).matchAll(re)];
    if (entries.length !== cps.length + 1)
        throw new Error(`expected ${cps.length + 1} glyphs, found ${entries.length}`);

    const digit = i => cps[i - 1] >= 0x30 && cps[i - 1] <= 0x39;
    const maxAdv = Math.max(...entries.filter((_, i) => i && digit(i)).map(m => +m[2]));
    let body = src.slice(start, end);
    entries.forEach((m, i) => {
        if (!i || !digit(i)) return;
        const shift = Math.round((maxAdv - m[2]) / 32);     // half the slack, in px
        body = body.replace(m[0],
            `{.bitmap_index = ${m[1]}, .adv_w = ${maxAdv}, .box_w = ${m[3]}, .box_h = ${m[4]}, .ofs_x = ${+m[5] + shift}, .ofs_y = ${m[6]}}`);
    });
    return src.slice(0, start) + body + src.slice(end);
}

for (const f of FONTS) {
    const out = join(OUT, `${f.name}.c`);
    const hex = n => `0x${n.toString(16)}`;
    const ranges = f.ranges.flatMap(([a, b]) => ['-r', a === b ? hex(a) : `${hex(a)}-${hex(b)}`]);
    const args = [CONV, '--font', TTF, ...ranges, '--size', String(f.size), '--bpp', '4',
                  '--format', 'lvgl', '--no-compress', '--no-kerning',
                  '--lv-include', 'lvgl.h', '-o', out];   // symbol = file name
    execFileSync(process.execPath, args, { stdio: 'inherit' });

    let src = readFileSync(out, 'utf8');
    if (f.tabular) src = makeTabular(src, codepoints(f.ranges));
    writeFileSync(out, `// Generated by tools/fonts.mjs. Do not edit.\n${src}`);
    console.log(`wrote ${out}`);
}
